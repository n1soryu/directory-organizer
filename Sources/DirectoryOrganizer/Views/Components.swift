/// Starts the full run (text recognition + model), or shows its progress with Cancel.
struct OrganizeNowControl: View {
    @Environment(AppModel.self) private var model
    var compact = false

    var body: some View {
        if let run = model.organizing, compact {
            HStack(spacing: 10) {
                ProgressView(value: run.fraction).frame(width: 110)
                Text("\(Int(run.fraction * 100))%").font(.caption.monospacedDigit()).foregroundStyle(.secondary)
                Button("Cancel") { model.cancelOrganize() }.buttonStyle(SoftButtonStyle(tint: .red))
            }
            // Room between the bar and the edge of its capsule.
            .padding(.leading, 16)
            .padding(.trailing, 4)
            .padding(.vertical, 4)
            .background(Color.purple.opacity(0.08), in: Capsule())
        } else if let run = model.organizing {
            VStack(alignment: .leading, spacing: 6) {
                Label("Organizing…", systemImage: "wand.and.sparkles").font(.callout.weight(.semibold)).foregroundStyle(.purple)
                HStack(spacing: 10) {
                    ProgressView(value: run.fraction)
                    Text("\(Int(run.fraction * 100))%").font(.caption.monospacedDigit()).foregroundStyle(.secondary)
                    Button("Cancel") { model.cancelOrganize() }
                        .buttonStyle(SoftButtonStyle(tint: .red))
                }
                if let progress = run.progress, !progress.file.isEmpty {
                    Text("\(progress.step.rawValue) \(progress.file)")
                        .font(.caption).foregroundStyle(.secondary)
                        .lineLimit(1).truncationMode(.middle)
                }
                TimelineView(.periodic(from: run.started, by: 1)) { context in
                    Text("Running for \(Int(context.date.timeIntervalSince(run.started))) s")
                        .font(.caption2).foregroundStyle(.tertiary)
                }
            }
            // Room between the bar and the panel's edge.
            .padding(14)
            .background(Color.purple.opacity(0.07), in: RoundedRectangle(cornerRadius: Theme.radius, style: .continuous))
        } else {
            Button {
                model.organizeNow()
            } label: {
                HStack(spacing: 8) {
                    Image(systemName: "wand.and.sparkles")
                    Text(compact ? "Organize Now" : organizeTitle)
                }
                .frame(maxWidth: compact ? nil : .infinity)
            }
            .buttonStyle(GradientButtonStyle(large: !compact))
            .disabled(model.isApplying || model.isLocked)
            .help("Read everything in full (text recognition) and ask the model about files no rule can place")
        }
    }

    private var organizeTitle: String {
        model.waiting.isEmpty ? "Organize Now" : "Organize Now (\(model.waiting.count) waiting)"
    }
}

/// Files the quick scan left for Organize Now (or, given `items`, any waiting files).
struct WaitingList: View {
    @Environment(AppModel.self) private var model
    var items: [WaitingItem]?
    var limit = 50

    var body: some View {
        let shown = items ?? model.waiting
        VStack(alignment: .leading, spacing: 4) {
            ForEach(shown.prefix(limit)) { item in
                HStack(spacing: 6) {
                    FileIcon(url: item.source)
                    Text(item.name).lineLimit(1).truncationMode(.middle)
                    Spacer()
                    Text(item.reason).font(.caption).foregroundStyle(.secondary).lineLimit(1)
                }
                .font(.callout)
            }
            if shown.count > limit {
                Text("and \(shown.count - limit) more").font(.caption).foregroundStyle(.secondary)
            }
        }
    }
}
